/**
 * 様式化した顔の高さ場(手続き生成)。u: 左右 -1..1、v: 上下 -1..1(上が正)。
 * 返り値は 0..1 程度の相対的な高さ。
 */
function g(x: number, s: number): number {
  return Math.exp(-(x * x) / (s * s));
}

export function faceHeight(u: number, v: number): number {
  const au = Math.abs(u);
  // 顔全体のドーム
  const dome = Math.max(0, 1 - (u / 0.9) ** 2 - (v / 1.05) ** 2);
  let h = Math.sqrt(dome) * 0.42;
  // 額
  h += 0.06 * g(v - 0.55, 0.35) * g(u, 0.6);
  // 眉
  h += 0.09 * g(v - 0.33, 0.07) * g(au - 0.33, 0.24);
  // 眼窩(くぼみ)
  h -= 0.14 * g(au - 0.34, 0.17) * g(v - 0.2, 0.11);
  // 鼻筋と鼻先
  const bridge = g(u, 0.11) * (v > -0.22 && v < 0.35 ? 1 : g(v > 0 ? v - 0.35 : v + 0.22, 0.08));
  h += 0.28 * bridge * (0.55 + 0.45 * Math.max(0, Math.min(1, (0.35 - v) / 0.57)));
  h += 0.16 * g(u, 0.16) * g(v + 0.2, 0.09);
  // 小鼻
  h += 0.07 * g(au - 0.17, 0.08) * g(v + 0.24, 0.07);
  // 頬
  h += 0.09 * g(au - 0.52, 0.24) * g(v + 0.05, 0.22);
  // 口(上唇・下唇)と口のくぼみ
  h += 0.07 * g(u, 0.3) * g(v + 0.46, 0.045);
  h += 0.06 * g(u, 0.26) * g(v + 0.58, 0.05);
  h -= 0.04 * g(u, 0.3) * g(v + 0.52, 0.025);
  // 顎
  h += 0.1 * g(u, 0.26) * g(v + 0.8, 0.13);
  return Math.max(0, h);
}
